package com.xiakexing.client.feature.shell

private fun buildSheet(
    source: PopupSource,
    title: String,
    showHeaderTitle: Boolean = true,
    subtitle: String = "",
    dialogId: String = "",
    dialogSource: String = "",
    detailLines: List<String> = emptyList(),
    interactionLines: List<String> = emptyList(),
    items: List<ShellSheetItem> = emptyList(),
    actions: List<ShellAction> = emptyList(),
    actionGroups: List<ShellActionGroup> = emptyList(),
    activeActionGroupId: String = "root",
    primaryAction: ShellAction? = null,
    panelMode: ShellPanelMode = ShellPanelMode.NONE,
    panelTabs: List<ShellAction> = emptyList(),
    panelSelectedTabId: String = "",
    panelCards: List<ShellPanelCard> = emptyList(),
    panelAllCards: List<ShellPanelCard> = emptyList(),
    panelStats: List<String> = emptyList(),
    mapContent: ShellMapPanelContent? = null,
    panelEmptyText: String = "暂无内容",
    emptyPresentation: ShellSheetEmptyPresentation = ShellSheetEmptyPresentation.SILENT,
    interactionTargetId: String = "",
    interactionTargetUiKey: String = "",
    interactionTargetKind: InteractionObjectKind? = null,
    interactionMode: InteractionSheetMode = InteractionSheetMode.DETAIL,
    compactPanel: Boolean = false,
    loading: Boolean = false,
    presentation: ShellSheetPresentation = ShellSheetPresentation.DEFAULT,
    errorMessage: String = "",
    retryAction: ShellAction? = null,
    navigation: SheetNavigationMeta = SheetNavigationMeta(),
    kind: ShellSheetKind = ShellSheetKind.UNKNOWN,
    headerText: String = "",
): ShellSheetState {
    return ShellSheetState(
        source = source,
        title = title,
        showHeaderTitle = showHeaderTitle,
        subtitle = subtitle,
        dialogId = dialogId,
        dialogSource = dialogSource,
        detailLines = detailLines,
        interactionLines = interactionLines,
        items = items,
        actions = actions,
        actionGroups = actionGroups,
        activeActionGroupId = activeActionGroupId,
        primaryAction = primaryAction,
        panelMode = panelMode,
        panelTabs = panelTabs,
        panelSelectedTabId = panelSelectedTabId,
        panelCards = panelCards,
        panelAllCards = panelAllCards,
        panelStats = panelStats,
        mapContent = mapContent,
        panelEmptyText = panelEmptyText,
        emptyPresentation = emptyPresentation,
        interactionTargetId = interactionTargetId,
        interactionTargetUiKey = interactionTargetUiKey,
        interactionTargetKind = interactionTargetKind,
        interactionMode = interactionMode,
        compactPanel = compactPanel,
        loading = loading,
        presentation = presentation,
        errorMessage = errorMessage,
        retryAction = retryAction,
        navigation = navigation,
        kind = kind,
        headerText = headerText,
    )
}

